// Generate `<name>.module.d.css.ts` beside each CSS module from the class map Vite
// itself computes (`css.modules.getJSON`), so `import x from "./x.module.css"` is
// typed by its real class names (tsconfig `allowArbitraryExtensions`) and a typo'd
// class fails `tsc`. `--check` writes nothing and exits 1 when a file is stale.
import { readFile, writeFile } from "node:fs/promises";
import { basename, join, relative } from "node:path";
import { build } from "vite";

const BUILDER = join(import.meta.dirname, "..");
const check = process.argv.includes("--check");

const maps = new Map<string, Record<string, string>>();
await build({
  configFile: join(BUILDER, "vite.config.ts"),
  logLevel: "error",
  css: {
    modules: {
      getJSON: (cssFile, json) => {
        maps.set(cssFile, json);
      },
    },
  },
  build: { write: false, rolldownOptions: { input: join(BUILDER, "src", "styles", "_all.ts") } },
});

const key = (k: string): string => (/^[A-Za-z_$][\w$]*$/u.test(k) ? k : JSON.stringify(k));

const declaration = (cssFile: string, json: Record<string, string>): string => {
  const fields = Object.entries(json)
    .toSorted(([a], [b]) => (a < b ? -1 : Number(a > b)))
    .map(([k, scoped]) => `  readonly ${key(k)}: ${JSON.stringify(scoped)};\n`)
    .join("");
  return `// Generated by \`just css-types\` from ${basename(cssFile)} -- do not edit.\ndeclare const classes: {\n${fields}};\nexport default classes;\n`;
};

const readOrEmpty = async (path: string): Promise<string> => {
  try {
    return await readFile(path, "utf8");
  } catch {
    return "";
  }
};

const stale: string[] = [];
await Promise.all(
  [...maps].map(async ([cssFile, json]) => {
    const path = cssFile.replace(/\.css$/u, ".d.css.ts");
    const text = declaration(cssFile, json);
    if ((await readOrEmpty(path)) === text) {
      return;
    }
    stale.push(relative(BUILDER, path));
    if (!check) {
      await writeFile(path, text);
    }
  }),
);

if (stale.length > 0) {
  console.log(`css-types: ${check ? "stale" : "wrote"} ${stale.toSorted().join(", ")}`);
  if (check) {
    console.log("  run `just css-types`");
    process.exit(1);
  }
}
